    # 공백 제거 후 매칭
    normalized = article_name.replace(" ", "")
    for key, value in REGULATION_TEXTS.items():
        if key.replace(" ", "") == normalized:
            return value
    # '제N조' 부분 매칭
    import re
    match = re.search(r"제(\d+)조", article_name)
    if match:
        article_num = match.group(0)
        for key, value in REGULATION_TEXTS.items():
            if article_num in key:
                return value
    return ""
