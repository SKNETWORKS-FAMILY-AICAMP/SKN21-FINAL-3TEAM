# confidence 값을 다양화하기 위한 매핑
CONFIDENCE_MAP = {
    # 기존 confidence → 다양화된 범위
    "yes": [0.88, 0.90, 0.91, 0.92, 0.93, 0.94, 0.95],
    "no": [0.82, 0.85, 0.87, 0.88, 0.90, 0.92, 0.93],
    "conditional": [0.62, 0.65, 0.68, 0.70, 0.73, 0.75, 0.78, 0.80, 0.82, 0.85],
    "no_regulation": [0.35, 0.38, 0.40, 0.42, 0.45, 0.48, 0.50, 0.52, 0.55],
}


def build_no_regulation_entry(scenario):
    """no_regulation 시나리오 → JSONL entry 생성"""
    article, question_template, reasoning, alternatives = scenario
    reg_text = REGULATIONS[article]
    person = rand_person()
    question = question_template.format(person=person)

    conf = random.choice(CONFIDENCE_MAP["no_regulation"])

    user_content = f"## 관련 규정 문서\n### {article}\n{reg_text}\n\n## 사용자 질문\n{question}"
    assistant_content = json.dumps({
        "result": "no_regulation",
        "confidence": conf,
        "reasoning": reasoning,
        "regulations": [{"article": article, "relevance": "낮음", "content": f"해당 규정은 질문과 직접적으로 관련이 없습니다."}],
        "cross_references": [],
        "conditions": None,
        "alternatives": alternatives,
    }, ensure_ascii=False)

    return {
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_content},
            {"role": "assistant", "content": assistant_content},
        ]
    }


def diversify_confidence(entry):
    """기존 entry의 confidence 값을 다양화"""
    entry = copy.deepcopy(entry)
    assistant_msg = entry["messages"][2]["content"]
    try:
        data = json.loads(assistant_msg)
        result = data.get("result", "")
        if result in CONFIDENCE_MAP:
            data["confidence"] = random.choice(CONFIDENCE_MAP[result])
            entry["messages"][2]["content"] = json.dumps(data, ensure_ascii=False)
    except json.JSONDecodeError:
        pass
    return entry


def load_jsonl(path):
    samples = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                samples.append(json.loads(line))
    return samples


def save_jsonl(samples, path):
    with open(path, "w", encoding="utf-8") as f:
        for s in samples:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")


def main():
    print("=" * 60)
    print("  v1_judgment 데이터 품질 개선")
    print("=" * 60)

    # 1. 백업
    print("\n[1/4] 기존 데이터 백업...")
    train_data = load_jsonl(TRAIN_PATH)
    eval_data = load_jsonl(EVAL_PATH)
    save_jsonl(train_data, BACKUP_TRAIN)
    save_jsonl(eval_data, BACKUP_EVAL)
    print(f"  백업 완료: train {len(train_data)}건, eval {len(eval_data)}건")

    # 2. no_regulation 데이터 생성
    print(f"\n[2/4] no_regulation 데이터 {len(NO_REG_SCENARIOS)}건 생성...")
    no_reg_entries = [build_no_regulation_entry(s) for s in NO_REG_SCENARIOS]
    random.shuffle(no_reg_entries)

    # train/eval 분할 (85:15)
    eval_count = max(1, int(len(no_reg_entries) * 0.15))
    no_reg_eval = no_reg_entries[:eval_count]
    no_reg_train = no_reg_entries[eval_count:]
    print(f"  생성: train {len(no_reg_train)}건, eval {len(no_reg_eval)}건")

    # 3. 기존 데이터 confidence 다양화
    print("\n[3/4] confidence 값 다양화...")
    old_confidences = set()
    for entry in train_data:
        try:
            data = json.loads(entry["messages"][2]["content"])
            old_confidences.add(data.get("confidence", 0))
        except:
            pass
    print(f"  기존 confidence 종류: {sorted(old_confidences)}")

    train_data = [diversify_confidence(e) for e in train_data]
    eval_data = [diversify_confidence(e) for e in eval_data]

    new_confidences = set()
    for entry in train_data:
        try:
            data = json.loads(entry["messages"][2]["content"])
            new_confidences.add(data.get("confidence", 0))
        except:
            pass
    print(f"  새 confidence 종류: {sorted(new_confidences)}")

    # 4. 합치기 + 저장
    print("\n[4/4] 데이터 합치기 + 저장...")
    train_data.extend(no_reg_train)
    eval_data.extend(no_reg_eval)
    random.shuffle(train_data)
    random.shuffle(eval_data)

    save_jsonl(train_data, TRAIN_PATH)
    save_jsonl(eval_data, EVAL_PATH)

    # 결과 통계
    print("\n" + "=" * 60)
    print("  최종 결과")
    print("=" * 60)
    print(f"  Train: {len(train_data)}건 (기존 {len(train_data)-len(no_reg_train)} + no_reg {len(no_reg_train)})")
    print(f"  Eval:  {len(eval_data)}건 (기존 {len(eval_data)-len(no_reg_eval)} + no_reg {len(no_reg_eval)})")
    print(f"  Total: {len(train_data) + len(eval_data)}건")

    # result 분포 확인
    for name, data in [("Train", train_data), ("Eval", eval_data)]:
        dist = {}
        for entry in data:
            try:
                result = json.loads(entry["messages"][2]["content"])["result"]
                dist[result] = dist.get(result, 0) + 1
            except:
                pass
        print(f"\n  {name} 분포:")
        for k in sorted(dist.keys()):
            pct = dist[k] / len(data) * 100
            print(f"    {k:<15} {dist[k]:>5}건 ({pct:.1f}%)")

    print("\n  완료!")


if __name__ == "__main__":
    main()
